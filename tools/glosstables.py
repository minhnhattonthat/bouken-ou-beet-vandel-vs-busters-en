"""glosstables.py: regenerate glossary.md's "Names from the game tables" section from the translated arm9 name
tables, so dialogue batches use the same item / monster / skill / place names as the menus. Reports JP terms whose
table English differs from a hand-written glossary row (fix one of them).

    python -X utf8 tools/glosstables.py [--dry]
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import batches  # noqa: E402

KINDS = ('item.name', 'keyitem.name', 'monster.name', 'weapon.name', 'armor.name', 'skill.name', 'special.name',
         'tengeki.name', 'meigeki.name', 'area.name', 'area2.name', 'vandel.name', 'buster.name', 'wpntype.name')
HEAD = '## Names from the game tables'
NEXT = '## Guidance'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry', action='store_true')
    a = ap.parse_args()
    text = batches.GLOSSARY.read_text(encoding='utf-8')
    if HEAD in text:
        pre, rest = text.split(HEAD, 1)
        post = rest[rest.index(NEXT):]
    else:
        pre, post = text.split(NEXT, 1)
        post = NEXT + post
    hand = {jp: en for jp, en, _ in batches.glossary_rows(pre)}
    rows, seen = [], set()
    for f, e in batches.all_entries(batches.load_files()):
        if e['kind'] in KINDS and e.get('en') and e['jp'] not in seen and len(e['jp']) > 1:
            seen.add(e['jp'])
            if e['jp'] in hand:
                if hand[e['jp']].lower() != e['en'].lower():
                    print('conflict: %s glossary %r, table %s %r' % (e['jp'], hand[e['jp']], e['kind'], e['en']))
                continue
            rows.append('| %s | %s |  | %s |  |' % (e['jp'], e['en'], e['kind']))
    sec = (HEAD + '\n\nGenerated by tools/glosstables.py from the translated tables (binding; change the table entry, '
           'then rerun).\n\n| JP | EN | max | notes | Avoid |\n|---|---|---|---|---|\n' + '\n'.join(rows) + '\n\n')
    print(len(rows), 'table names')
    if not a.dry:
        batches.GLOSSARY.write_text(pre + sec + post, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
