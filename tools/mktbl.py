"""mktbl.py: generate tbl/jp.tbl from the font order (docs/re/text.md).

    python -X utf8 tools/mktbl.py      # writes tbl/jp.tbl

Text code (16-bit LE) = font glyph index + 1. Font rows of 94 cells map to JIS X 0208 rows: font rows 0-7 -> ku 1-8,
font row 8 -> ku 13 (NEC special characters), font rows 9-77 -> ku 16-84. Characters are decoded through Shift-JIS
(cp932) so row 13 resolves. Unassigned cells are left out (they decode as [XX] hex escapes).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NGLYPH = 7332

# Control codes (meaning: docs/re/text.md). Argument counts are in 16-bit words, written as bytes for tbl.py.
CONTROLS = {
    0x0000: "{end}",
    0xFF70: "{br}",     # line break (verified on screen)
    0xFF71: "{close}",  # wait, close message (guess)
    0xFF72: "{page}",   # wait, clear box (guess)
    0xFF90: "{hero}",   # Buster-story player name (guess: alone as a speaker; 250 uses)
    0xFF92: "{vandel}",  # Vandel-story player name (guess: alone as a speaker in Vandel scenes; 82 uses)
    0xFF93: "{name93}",  # a name in quotes, rom.49BA8 「..」だっ！！ (unknown; 1 use)
    0xFFA4: "{monster}",  # quest target monster name (guess: 「..の討伐」 quest titles)
    0xFFA5: "{count}",  # quest kill count (guess: 「..を..匹倒してほしい」)
}


def font_ku(row):
    if row < 8:
        return row + 1
    if row == 8:
        return 13
    return row + 7


def jis_to_sjis(ku, ten):
    j1, j2 = ku + 0x20, ten + 0x20
    s1 = (j1 + 1) // 2 + (0x70 if j1 <= 0x5E else 0xB0)
    s2 = j2 + (0x1F if j1 % 2 else 0x7E)
    if j1 % 2 and s2 >= 0x7F:
        s2 += 1
    return bytes([s1, s2])


def code_char(code):
    i = code - 1
    if not 0 <= i < NGLYPH:
        return None
    ku, ten = font_ku(i // 94), i % 94 + 1
    try:
        ch = jis_to_sjis(ku, ten).decode("cp932")
    except UnicodeDecodeError:
        return None
    return ch


def lines():
    yield "# Generated by tools/mktbl.py; do not edit by hand. Key = 16-bit LE code bytes."
    for code, val in CONTROLS.items():
        yield f"{code.to_bytes(2, 'little').hex().upper()}={val}"
    for code in range(1, NGLYPH + 1):
        ch = code_char(code)
        if ch is None:
            continue
        val = r"\s" if ch == " " else ch
        yield f"{code.to_bytes(2, 'little').hex().upper()}={val}"


if __name__ == "__main__":
    out = ROOT / "tbl" / "jp.tbl"
    out.parent.mkdir(exist_ok=True)
    text = "\n".join(lines()) + "\n"
    out.write_text(text, encoding="utf-8", newline="\n")
    print(out, text.count("\n"), "lines")
