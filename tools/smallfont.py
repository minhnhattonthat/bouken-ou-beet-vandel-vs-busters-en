def _parse():
    lines = _SRC.strip('\n').split('\n')
    out, i = {}, 0
    while i < len(lines):
        ch = lines[i]
        rows = lines[i + 1:i + 1 + ROWS]
        w = max(len(r) for r in rows)
        out[ch] = [[1 if c == '#' else 0 for c in r.ljust(w, '.')] for r in rows]
        i += 1 + ROWS
    out[' '] = [[0, 0] for _ in range(ROWS)]
    return out


GLYPHS = _parse()
